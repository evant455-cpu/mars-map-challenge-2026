# ZERO-DEPENDENCY NUMPY RGBA -> BASE64 PNG ENCODER & COLORMAPS
# ==============================================================================
def encode_rgba_to_png_base64(rgba: np.ndarray) -> str:
    """Encodes an (H, W, 4) uint8 RGBA array into a base64 PNG data URI.

    Args:
        rgba: 3D NumPy uint8 array of shape `(rows, cols, 4)`.

    Returns:
        Base64-encoded PNG data URI string (`data:image/png;base64,...`).
    """
    if rgba.ndim != 3 or rgba.shape[2] != 4 or rgba.dtype != np.uint8:
        raise ValueError(f"Expected (H, W, 4) uint8 array, got {rgba.shape} {rgba.dtype}")

    rows, cols, _ = rgba.shape

    def _png_chunk(chunk_type: bytes, data: bytes) -> bytes:
        chunk = chunk_type + data
        crc = zlib.crc32(chunk) & 0xFFFFFFFF
        return struct.pack("!I", len(data)) + chunk + struct.pack("!I", crc)

    png_sig = b"\x89PNG\r\n\x1a\n"
    ihdr_data = struct.pack("!IIBBBBB", cols, rows, 8, 6, 0, 0, 0)
    ihdr = _png_chunk(b"IHDR", ihdr_data)

    raw_scanlines = b"".join(b"\x00" + rgba[r].tobytes() for r in range(rows))
    compressed = zlib.compress(raw_scanlines, level=6)
    idat = _png_chunk(b"IDAT", compressed)
    iend = _png_chunk(b"IEND", b"")

    png_bytes = png_sig + ihdr + idat + iend
    b64_str = base64.b64encode(png_bytes).decode("ascii")
    return f"data:image/png;base64,{b64_str}"


def _interpolate_colormap(
    norm_vals: np.ndarray, stops: List[Tuple[float, Tuple[int, int, int]]]
) -> np.ndarray:
    """Maps normalized [0, 1] values to an (H, W, 4) uint8 RGBA image via RGB stops."""
    rows, cols = norm_vals.shape
    rgba = np.zeros((rows, cols, 4), dtype=np.uint8)
    rgba[:, :, 3] = 255

    positions = np.array([s[0] for s in stops], dtype=np.float64)
    reds = np.array([s[1][0] for s in stops], dtype=np.float64)
    greens = np.array([s[1][1] for s in stops], dtype=np.float64)
    blues = np.array([s[1][2] for s in stops], dtype=np.float64)

    flat = np.clip(norm_vals.ravel(), 0.0, 1.0)
    rgba[:, :, 0] = np.interp(flat, positions, reds).astype(np.uint8).reshape(rows, cols)
    rgba[:, :, 1] = np.interp(flat, positions, greens).astype(np.uint8).reshape(rows, cols)
    rgba[:, :, 2] = np.interp(flat, positions, blues).astype(np.uint8).reshape(rows, cols)
    return rgba


def render_raster_layers(
    dem: np.ndarray,
    slope_deg: np.ndarray,
    rock_protrusion_m: np.ndarray,
    hazard_tier: np.ndarray,
    no_go_mask: np.ndarray,
    resolution_m: float,
    time_to_base_sec: Optional[np.ndarray] = None,
) -> Dict[str, str]:
    """Renders all base and overlay raster layers into base64 PNG data URIs."""
    rows, cols = dem.shape

    # 1. Discrete 4-Tier Hazard & Obstacle Layer
    tier_rgba = np.zeros((rows, cols, 4), dtype=np.uint8)
    tier_rgba[:, :, 3] = 255
    palette = {
        0: (27, 67, 50),     # Tier 0: Nominal
        1: (233, 196, 106),  # Tier 1: Caution
        2: (244, 162, 97),   # Tier 2: High-Cost
        3: (214, 40, 40),    # Tier 3: No-Go
    }
    for tier_id, rgb in palette.items():
        mask = hazard_tier == tier_id
        tier_rgba[mask, 0] = rgb[0]
        tier_rgba[mask, 1] = rgb[1]
        tier_rgba[mask, 2] = rgb[2]

    # 2. Shaded Relief Elevation (Hillshade + Martian Hypsometric Tint)
    dem_filled = np.nan_to_num(dem, nan=float(np.nanmin(dem)))
    dz_dy, dz_dx = np.gradient(dem_filled, resolution_m)
    az_rad = np.radians(315.0)
    alt_rad = np.radians(38.0)
    slope_rad = np.arctan(np.hypot(dz_dx, dz_dy) * 1.6)
    aspect_rad = np.arctan2(-dz_dx, dz_dy)
    shade = (
        np.sin(alt_rad) * np.cos(slope_rad)
        + np.cos(alt_rad) * np.sin(slope_rad) * np.cos(az_rad - aspect_rad)
    )
    shade_norm = np.clip(0.35 + 0.75 * shade, 0.25, 1.25)

    z_min, z_max = float(np.nanmin(dem_filled)), float(np.nanmax(dem_filled))
    z_norm = (dem_filled - z_min) / max(1e-6, z_max - z_min)
    mars_elev_stops = [
        (0.00, (58, 42, 38)),
        (0.25, (118, 72, 54)),
        (0.55, (176, 114, 78)),
        (0.80, (217, 162, 115)),
        (1.00, (245, 218, 184)),
    ]
    dem_rgba = _interpolate_colormap(z_norm, mars_elev_stops)
    for ch in range(3):
        dem_rgba[:, :, ch] = np.clip(
            dem_rgba[:, :, ch].astype(np.float64) * shade_norm, 0, 255
        ).astype(np.uint8)

    # 3. Terrain Slope Layer (0 to 25+ deg)
    slope_norm = np.nan_to_num(slope_deg / 25.0, nan=1.0)
    slope_stops = [
        (0.00, (15, 12, 41)),
        (0.25, (75, 29, 111)),
        (0.50, (168, 50, 111)),
        (0.75, (241, 115, 56)),
        (0.88, (252, 210, 89)),
        (1.00, (255, 45, 45)),
    ]
    slope_rgba = _interpolate_colormap(slope_norm, slope_stops)

    # 4. Rock Protrusion Index Layer
    prot_norm = np.nan_to_num(rock_protrusion_m / 0.75, nan=0.0)
    rock_stops = [
        (0.00, (18, 24, 38)),
        (0.25, (32, 58, 82)),
        (0.45, (56, 189, 248)),
        (0.85, (250, 204, 21)),
        (1.00, (239, 68, 68)),
    ]
    rock_rgba = _interpolate_colormap(prot_norm, rock_stops)

    # 5. Fifth Base Layer: Time-to-Safety (Green near Base -> Yellow -> Red far away)
    if time_to_base_sec is not None and np.any(np.isfinite(time_to_base_sec)):
        finite_mask = np.isfinite(time_to_base_sec)
        max_sec = max(60.0, float(np.nanmax(time_to_base_sec[finite_mask])))
        ttb_norm = np.where(finite_mask, time_to_base_sec / max_sec, 1.0)
        safety_stops = [
            (0.00, (16, 185, 129)),   # Emerald Green at Base (0 min)
            (0.30, (132, 204, 22)),   # Lime Green nearby
            (0.55, (250, 204, 21)),   # Amber Yellow mid-range
            (0.80, (249, 115, 22)),   # Deep Orange
            (1.00, (220, 38, 38)),    # Alert Crimson far away
        ]
        safety_rgba = _interpolate_colormap(ttb_norm, safety_stops)
        # Shade No-Go / unreachable cells dark slate so cliffs & boulders stand out clearly
        safety_rgba[~finite_mask] = [17, 24, 39, 255]
    else:
        safety_rgba = tier_rgba.copy()

    # 6. Transparent No-Go Perimeter Outline Overlay
    padded_ng = np.pad(no_go_mask, pad_width=1, mode="constant", constant_values=False)
    eroded_ng = (
        padded_ng[:-2, 1:-1]
        & padded_ng[2:, 1:-1]
        & padded_ng[1:-1, :-2]
        & padded_ng[1:-1, 2:]
    )
    boundary = no_go_mask & (~eroded_ng)
    outline_rgba = np.zeros((rows, cols, 4), dtype=np.uint8)
    outline_rgba[boundary] = [255, 77, 109, 235]

    return {
        "hazard": encode_rgba_to_png_base64(tier_rgba),
        "safety": encode_rgba_to_png_base64(safety_rgba),
        "dem": encode_rgba_to_png_base64(dem_rgba),
        "slope": encode_rgba_to_png_base64(slope_rgba),
        "rock": encode_rgba_to_png_base64(rock_rgba),
        "nogo_outline": encode_rgba_to_png_base64(outline_rgba),
    }


