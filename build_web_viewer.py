def setup_viewer_logger(log_path: Path, level: int = logging.INFO) -> logging.Logger:
    """Configures a dual-output logger for terminal and mobile SSH inspection.

    Args:
        log_path: Destination file path for persistent builder logs.
        level: Logging severity threshold.

    Returns:
        Configured logging.Logger instance.
    """
    logger = logging.getLogger("MartianEVAViewerBuilder")
    logger.setLevel(level)

    if logger.handlers:
        logger.handlers.clear()

    formatter = logging.Formatter(
        fmt="%(asctime)s | %(levelname)-7s | %(funcName)s:%(lineno)d | %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    )

    file_handler = logging.FileHandler(log_path, mode="a", encoding="utf-8")
    file_handler.setFormatter(formatter)
    logger.addHandler(file_handler)

    stream_handler = logging.StreamHandler(sys.stdout)
    stream_handler.setFormatter(formatter)
    logger.addHandler(stream_handler)

    return logger


